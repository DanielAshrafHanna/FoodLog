create or replace function private.enforce_three_active_votes()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  if new.deleted_at is null and (
    select count(*)
    from public.decision_votes
    where session_id = new.session_id
      and lower(voter_email) = lower(new.voter_email)
      and deleted_at is null
      and id <> new.id
