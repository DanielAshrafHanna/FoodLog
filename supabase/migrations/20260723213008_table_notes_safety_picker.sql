-- Save each journal record and the current editor's rating/review in one transaction.
-- Media is uploaded before the dish RPC. If this transaction fails, no committed row
-- can reference the new path, so the client may safely remove only that new orphan.
create or replace function public.save_restaurant_with_rating(
  p_restaurant jsonb,
  p_rating numeric default null,
  p_restaurant_id uuid default null
)
returns uuid
language plpgsql
security invoker
set search_path = ''
as $save_restaurant$
declare
  saved_id uuid := p_restaurant_id;
  actor_email text := lower(coalesce((select auth.jwt() ->> 'email'), ''));
  actor_name text := coalesce(nullif(p_restaurant ->> 'updated_by', ''), split_part(actor_email, '@', 1));
begin
  if not public.is_approved_editor() then
    raise exception 'Only approved editors can save restaurants.';
  end if;

  if nullif(trim(p_restaurant ->> 'name'), '') is null then
    raise exception 'Restaurant name is required.';
  end if;

  if saved_id is null then
    insert into public.restaurants (
      name, location, cuisine, playlist, playlists, price, maps, notes, visited,
      updated_at, updated_by
    )
    values (
      trim(p_restaurant ->> 'name'),
      coalesce(p_restaurant ->> 'location', ''),
      coalesce(p_restaurant ->> 'cuisine', ''),
      coalesce(p_restaurant ->> 'playlist', ''),
      coalesce(
        array(select jsonb_array_elements_text(coalesce(p_restaurant -> 'playlists', '[]'::jsonb))),
        '{}'::text[]
      ),
      coalesce(p_restaurant ->> 'price', '$$'),
      coalesce(p_restaurant ->> 'maps', ''),
      coalesce(p_restaurant ->> 'notes', ''),
      coalesce(
        array(select jsonb_array_elements_text(coalesce(p_restaurant -> 'visited', '[]'::jsonb))),
        '{}'::text[]
      ),
      now(),
      actor_name
    )
    returning id into saved_id;
  else
    update public.restaurants
    set
      name = trim(p_restaurant ->> 'name'),
      location = coalesce(p_restaurant ->> 'location', ''),
      cuisine = coalesce(p_restaurant ->> 'cuisine', ''),
      playlist = coalesce(p_restaurant ->> 'playlist', ''),
      playlists = coalesce(
        array(select jsonb_array_elements_text(coalesce(p_restaurant -> 'playlists', '[]'::jsonb))),
        '{}'::text[]
      ),
      price = coalesce(p_restaurant ->> 'price', '$$'),
      maps = coalesce(p_restaurant ->> 'maps', ''),
      notes = coalesce(p_restaurant ->> 'notes', ''),
      visited = coalesce(
        array(select jsonb_array_elements_text(coalesce(p_restaurant -> 'visited', '[]'::jsonb))),
        '{}'::text[]
      ),
      updated_at = now(),
      updated_by = actor_name
    where id = saved_id and deleted_at is null;

    if not found then
      raise exception 'Restaurant is unavailable or in Trash.';
    end if;
  end if;

  if p_rating is null then
    update public.restaurant_ratings
    set deleted_at = now(), deleted_by = actor_email
    where restaurant_id = saved_id
      and lower(rater_email) = actor_email
      and deleted_at is null;
  else
    if p_rating < 0.5 or p_rating > 5 then
      raise exception 'Rating must be between 0.5 and 5.';
    end if;
    insert into public.restaurant_ratings (
      restaurant_id, rater_email, rater_name, rating, deleted_at, deleted_by
    )
    values (saved_id, actor_email, actor_name, p_rating, null, null)
    on conflict (restaurant_id, rater_email)
    do update set
      rater_name = excluded.rater_name,
      rating = excluded.rating,
      deleted_at = null,
      deleted_by = null;
  end if;

  return saved_id;
end;
$save_restaurant$;

