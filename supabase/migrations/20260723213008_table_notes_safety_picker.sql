create or replace function public.close_decision_session(p_session_id uuid)
returns uuid
language plpgsql
security invoker
set search_path = ''
as $$
declare
  selected_id uuid;
begin
  if not exists (
    select 1 from public.decision_sessions
    where id = p_session_id
      and status = 'open'
      and (
        public.is_foodlog_owner()
        or lower(created_by) = lower(coalesce((select auth.jwt() ->> 'email'), ''))
      )
  ) then
    raise exception 'Only the session creator can close an open session.';
  end if;

  select ranked.restaurant_id
  into selected_id
  from (
    select
      candidates.restaurant_id,
      count(votes.id) as vote_count
    from public.decision_candidates candidates
    left join public.decision_votes votes
      on votes.session_id = candidates.session_id
     and votes.restaurant_id = candidates.restaurant_id
     and votes.deleted_at is null
    where candidates.session_id = p_session_id
      and candidates.deleted_at is null
    group by candidates.restaurant_id
  ) ranked
  order by ranked.vote_count desc, random()
  limit 1;

  if selected_id is null then
    raise exception 'Add at least one place before closing the session.';
  end if;

  update public.decision_sessions
  set
    status = 'closed',
    selected_restaurant_id = selected_id,
    decided_at = now(),
    updated_at = now()
  where id = p_session_id;

  return selected_id;
end;
$$;

