create or replace function private.log_foodlog_row_change()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  old_json jsonb := case when tg_op = 'INSERT' then null else to_jsonb(old) end;
  new_json jsonb := case when tg_op = 'DELETE' then null else to_jsonb(new) end;
  row_json jsonb := coalesce(new_json, old_json);
  record_id text;
  event_action text;
  actor text := lower(coalesce((select auth.jwt() ->> 'email'), 'system'));
begin
  record_id := coalesce(
    row_json ->> 'id',
    row_json ->> 'name',
    concat_ws(':', row_json ->> 'restaurant_id', row_json ->> 'rater_email'),
    concat_ws(':', row_json ->> 'dish_id', row_json ->> 'rater_email'),
    'unknown'
  );

  if tg_argv[0] in ('decision_sessions', 'decision_candidates', 'decision_votes') then
    event_action := 'picker';
  elsif tg_argv[0] in ('approved_users', 'pending_approvals') then
    event_action := 'admin';
  elsif tg_op = 'INSERT' and nullif(row_json ->> 'import_batch_id', '') is not null then
    event_action := 'import';
  elsif tg_op = 'INSERT' then
    event_action := 'create';
  elsif old_json ->> 'deleted_at' is null and new_json ->> 'deleted_at' is not null then
    event_action := 'trash';
  elsif old_json ->> 'deleted_at' is not null and new_json ->> 'deleted_at' is null then
    event_action := 'restore';
  else
    event_action := 'edit';
  end if;

  insert into public.activity_log (
    entity_type,
    entity_id,
    action,
    actor_email,
    before_state,
    after_state
  )
  values (tg_argv[0], record_id, event_action, actor, old_json, new_json);

  if tg_op = 'DELETE' then
    return old;
  end if;
  return new;
end;
$$;

revoke all on function private.log_foodlog_row_change() from public, anon, authenticated;

do $$
declare
  table_name text;
begin
  foreach table_name in array array[
    'restaurants',
    'dishes',
    'restaurant_photos',
    'restaurant_ratings',
    'dish_ratings',
    'playlists'
  ]
  loop
    if to_regclass('public.' || table_name) is not null then
      execute format('drop trigger if exists foodlog_activity on public.%I', table_name);
      execute format(
        'create trigger foodlog_activity after insert or update on public.%I for each row execute function private.log_foodlog_row_change(%L)',
        table_name,
        table_name
      );
    end if;
  end loop;
end
$$;

do $$
declare
  table_name text;
begin
  foreach table_name in array array['approved_users', 'pending_approvals']
  loop
    if to_regclass('public.' || table_name) is not null then
      execute format('drop trigger if exists foodlog_admin_activity on public.%I', table_name);
      execute format(
        'create trigger foodlog_admin_activity after insert or update or delete on public.%I for each row execute function private.log_foodlog_row_change(%L)',
        table_name,
        table_name
      );
    end if;
  end loop;
end
$$;

